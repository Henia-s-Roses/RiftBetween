// Crate.cs
// Breakable crate placed in the scene.
// Takes one hit to break. Has a 50% chance to drop an item on break.
// Swaps its sprite to match the active world.

using Mirror;
using UnityEngine;

public class Crate : NetworkBehaviour
{
    // ?? Inspector ?????????????????????????????????????????????????????????????

    [Header("World Skins")]
    [Tooltip("Wooden pixel crate — World A")]
    public Sprite worldASkin;

    [Tooltip("Ink-wrapped bundle — World B")]
    public Sprite worldBSkin;

    [Tooltip("Glitchy hovering container — Rift")]
    public Sprite riftSkin;

    [Header("Settings")]
    [Range(0f, 1f)]
    [Tooltip("Probability that breaking this crate drops an item (0.5 = 50%)")]
    public float dropChance = 0.5f;

    // ?? Component refs ????????????????????????????????????????????????????????

    private SpriteRenderer spriteRenderer;

    // ?? Lifecycle ?????????????????????????????????????????????????????????????

    private void Awake( )
    {
        spriteRenderer = GetComponent<SpriteRenderer>( );
    }

    public override void OnStartClient( )
    {
        WorldManager.OnWorldChanged += HandleWorldChanged;

        // Apply correct skin immediately on spawn
        if (WorldManager.Instance != null)
            HandleWorldChanged((WorldState)WorldManager.Instance.activeWorld);
    }

    private void OnDestroy( )
    {
        WorldManager.OnWorldChanged -= HandleWorldChanged;
    }

    // ?? Breaking ??????????????????????????????????????????????????????????????

    // Called by a player's attack hitbox on the server.
    [Server]
    public void Break( )
    {
        RiftLogger.Log("Crate broken", this);

        // Roll for drop
        if (Random.value <= dropChance)
        {
            GameObject prefab = ItemDropTable.Instance?.Roll( );
            if (prefab != null)
            {
                GameObject drop = Instantiate(prefab, transform.position, Quaternion.identity);
                NetworkServer.Spawn(drop);
                RiftLogger.Log($"Crate dropped item: {prefab.name}", this);
            }
        } else
        {
            RiftLogger.Log("Crate dropped nothing (50% miss)", this);
        }

        RpcPlayBreakEffect( );
        NetworkServer.Destroy(gameObject);
    }

    // ?? World skin swap ???????????????????????????????????????????????????????

    private void HandleWorldChanged(WorldState world)
    {
        if (spriteRenderer == null) return;

        spriteRenderer.sprite = world switch
        {
            WorldState.WorldA => worldASkin,
            WorldState.WorldB => worldBSkin,
            WorldState.Rift => riftSkin,
            _ => worldASkin
        };
    }

    // ?? VFX ???????????????????????????????????????????????????????????????????

