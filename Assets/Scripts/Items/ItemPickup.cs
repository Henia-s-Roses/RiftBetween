// ItemPickup.cs
// Abstract base for all item pickups.
// Handles the common overlap-detect flow on the server.
// Subclasses implement ApplyEffect() for their specific behavior.

using Mirror;
using UnityEngine;

public abstract class ItemPickup : NetworkBehaviour
{
    // ?? Inspector ?????????????????????????????????????????????????????????????

    [Header("Pickup Base")]
    public ItemType itemType;

    [Tooltip("Optional: bob/spin animation speed")]
    public float floatSpeed = 1.5f;
    public float floatHeight = 0.15f;

    // ?? State ?????????????????????????????????????????????????????????????????

    private Vector3 startPos;
    private bool collected = false;  // Prevents double-pickup on same frame

    // ?? Lifecycle ?????????????????????????????????????????????????????????????

    private void Start( )
    {
        startPos = transform.position;
    }

    // Gentle bob animation — runs on all clients, purely visual
    private void Update( )
    {
        float newY = startPos.y + Mathf.Sin(Time.time * floatSpeed) * floatHeight;
        transform.position = new Vector3(transform.position.x, newY, transform.position.z);
    }

    // ?? Pickup detection ??????????????????????????????????????????????????????

    private void OnTriggerEnter2D(Collider2D other)
    {
        if (!isServer) return;
        if (collected) return;

        var health = other.GetComponent<PlayerHealth>( );
        if (health == null) return;

        // Don't let downed players pick up items
        var revive = other.GetComponent<PlayerRevive>( );
        if (revive != null && revive.isDown) return;

        collected = true;

        RiftLogger.Log($"{itemType} picked up by {other.name}", this);

        ApplyEffect(other.gameObject);
        RpcOnPickedUp( );
        NetworkServer.Destroy(gameObject);
    }

    // ?? Interface for subclasses ??????????????????????????????????????????????

    // Server-side. Receives the player GameObject that walked over this item.
    protected abstract void ApplyEffect(GameObject player);

    // Fires on all clients — play pickup sound/VFX here.
    protected virtual void RpcOnPickedUp( )
    {
        // Instantiate pickup VFX here if needed
    }
}