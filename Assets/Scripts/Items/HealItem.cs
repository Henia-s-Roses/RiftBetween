// HealItem.cs
// Handles both SmallVial (heals one player) and SharedPotion (heals both).
// Which behavior is used depends on the itemType field set in the Inspector.

using Mirror;
using UnityEngine;

public class HealItem : ItemPickup
{
    // ?? Inspector ?????????????????????????????????????????????????????????????

    [Header("Heal Settings")]
    [Tooltip("HP restored. Applies to one player (SmallVial) or both (SharedPotion).")]
    public float healAmount = 30f;

    // ?? Effect ????????????????????????????????????????????????????????????????

    [Server]
    protected override void ApplyEffect(GameObject player)
    {
        if (itemType == ItemType.SharedPotion)
        {
            // Heal every connected player
            foreach (var p in FindObjectsOfType<PlayerHealth>( ))
            {
                p.Heal(healAmount);
                RiftLogger.Log($"SharedPotion healed {p.name} for {healAmount}", this);
            }
        } else
        {
            // SmallVial — heal only the player who picked it up
            var health = player.GetComponent<PlayerHealth>( );
            health?.Heal(healAmount);
            RiftLogger.Log($"SmallVial healed {player.name} for {healAmount}", this);
        }
    }
}